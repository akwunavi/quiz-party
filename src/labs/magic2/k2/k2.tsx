import type { CSSProperties } from 'react'
import { JP, BLITZ } from '../data'
import type { Kit, TimerProps, WorldProps } from '../kit'

const cv = (o: Record<string, string | number>) => o as CSSProperties

/** Куда смотрит лампа (горячее пятно на шёлке) в каждом состоянии. */
function lamp(st: string, sub: string): [number, number] {
  if (st === 'jp' && sub === 'select') return [360 + JP.open.theme * 300, 330 + JP.open.tile * 132]
  if (st === 'melody' && sub === 'chosen') return [960, 540]
  if (st === 'melody' && (sub === 'bids' || sub === 'reveal')) return [600, 480]
  if (st === 'blitz') {
    const i = BLITZ.order.indexOf(BLITZ.q.team), colW = (1640 - 78) / 4
    return [140 + (i % 4) * (colW + 26) + colW / 2, i < 4 ? 300 : 820]
  }
  if (st === 'lobby' || st === 'randomizer') return [1150, 560]
  if (st === 'final' && sub !== 'last') return [960, 330]
  if (st === 'scramble') return [960, 620]
  return [960, 420]
}

function World({ st, sub }: WorldProps) {
  const [lx, ly] = lamp(st, sub)
  const pass = (st === 'rules' || st === 'roundT') && sub === 'event'
  const act = st === 'cw' && sub === 'event'
  return (
    <div className="x-world k2-world" style={cv({ '--lx': `${lx}px`, '--ly': `${ly}px` })}>
      <div className="k2-silk" />
      <div className="k2-hot" />
      <div className="k2-weave" />
      <div className="k2-vig" />
      <div className="k2-dark" />
      <div className="k2-rod" />
      {pass && <svg className={`k2-pass x-front ${st === 'roundT' ? 'small' : ''}`} viewBox="0 0 1000 600" aria-hidden>
        {st === 'roundT'
          ? <g><rect x="490" y="0" width="8" height="600" /><path d="M 494 120 l 120 60 l -120 60 l -120 -60 z" /></g>
          : <path d="M 40 330 C 160 250 280 240 380 300 C 440 200 520 60 700 20 C 640 120 600 220 560 300 C 680 280 820 300 960 360 C 820 380 700 380 600 400 C 560 470 500 540 380 580 C 420 500 440 440 440 400 C 320 420 200 400 40 330 Z" />}
      </svg>}
      <div className={`k2-cur l x-front${act ? ' shut' : ''}`} /><div className={`k2-cur r x-front${act ? ' shut' : ''}`} />
      <div className="k2-val x-front" />
    </div>
  )
}

/** Таймер: затмение. Чёрный диск наползает на светящийся круг; на нуле остаётся корона. */
function Timer({ left, total, phase, size }: TimerProps) {
  const p = Math.max(0, Math.min(1, 1 - left / total))
  return (
    <div className={`k2-timer ts-${size} ph-${phase}`} style={cv({ '--p': p })}>
      <span className="k2-disc"><span className="k2-sun" /><span className="k2-moon" /></span><span className="k2-corona" />
      <b>{left}</b>
    </div>
  )
}

