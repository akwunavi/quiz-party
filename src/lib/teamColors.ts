// Один список на весь проект: проектор, админка, регистрация. Раньше палитры
// были разными и короткими — на большой игре цвета начинали повторяться
// уже на седьмой команде, и команды путали себя на табло.
//
// Порядок подобран так, чтобы СОСЕДНИЕ цвета максимально различались:
// на проекторе рядом стоят команда N и N+1, и похожие оттенки читаются плохо.
// Все цвета светлые и насыщенные — тёмные на чёрном фоне не видны.
export const TEAM_PALETTE = [
  '#ffd700', // золотой
  '#ff2fa0', // пурпурный
  '#00e5ff', // циан
  '#b6ff3c', // лайм
  '#ff8c42', // оранжевый
  '#9d7bff', // фиалковый
  '#ff5c5c', // коралловый
  '#40e0d0', // бирюзовый
  '#f7a1c4', // розовый
  '#7cf5a0', // мятный
  '#ffe066', // светло-жёлтый
  '#4dabf7', // небесный
  '#e599f7', // лиловый
  '#ffa8a8', // персиковый
  '#63e6be', // морская волна
  '#ffc078', // абрикосовый
  '#748ffc', // индиго
  '#d0bfff', // лавандовый
  '#8ce99a', // салатовый
  '#ff9f1c', // янтарный
  '#66d9e8', // голубой лёд
  '#faa2c1', // фламинго
  '#a9e34b', // травяной
  '#ff6b6b', // алый
]

/** Цвет по номеру команды. Повтор начнётся только после 24-й. */
export function teamColor(index: number): string {
  return TEAM_PALETTE[index % TEAM_PALETTE.length]
}

/** Свободный цвет: не занятый другими командами, иначе — по кругу. */
export function nextFreeColor(used: string[]): string {
  const free = TEAM_PALETTE.find(c => !used.includes(c))
  return free ?? TEAM_PALETTE[used.length % TEAM_PALETTE.length]
}
