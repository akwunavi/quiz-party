// ═══ Кто что может править в редакторе ═══
//
// Правило ОДНО и оно должно совпадать с политиками в базе (миграция 0006),
// иначе интерфейс либо прячет то, что разрешено, либо показывает кнопки,
// которые упрутся в отказ:
//
//   владелец                      — всё;
//   редактор с can_edit_all       — любые НЕприватные пакеты;
//   редактор без can_edit_all     — только пакеты, созданные им самим;
//   приватные пакеты              — только владелец.
//
// Отдельная история — статус `active` («ИДЁТ ИГРА»). Раньше он блокировал
// редактору ВСЁ: пропадали кнопки удаления, стрелки порядка, «добавить
// вопрос». Выглядело как поломка: человек видит свой пакет и не может ничего
// сделать, причём почему — нигде не сказано. Хуже того, статус залипает:
// пакет остаётся «в игре» после прогона, и правки закрыты навсегда.
// Теперь право правки статусом не отменяется, но интерфейс предупреждает,
// что пакет сейчас в игре и правки уедут на проектор сразу.
import type { EditorUser } from './auth'
import type { Pack } from '../types/quiz'

type PackLike = Pick<Pack, 'is_private' | 'created_by' | 'status'>

/** Можно ли этому человеку менять содержимое пакета. */
export function canEditPack(user: EditorUser, pack: PackLike): boolean {
  if (user.role === 'owner') return true
  if (pack.is_private) return false
  if (user.can_edit_all) return true
  return !!pack.created_by && pack.created_by === user.id
}

/** Почему правки недоступны — текстом для человека, а не молчаливой серостью. */
export function whyReadOnly(user: EditorUser, pack: PackLike): string | null {
  if (canEditPack(user, pack)) return null
  if (pack.is_private) return 'Пакет приватный: править его может только владелец.'
  return 'Пакет создал другой редактор. Тебе он доступен только для просмотра — '
    + 'попроси владельца открыть доступ к чужим пакетам.'
}

/** Пакет прямо сейчас играется: правки видны залу немедленно. */
export function isLiveNow(pack: PackLike): boolean {
  return pack.status === 'active'
}
