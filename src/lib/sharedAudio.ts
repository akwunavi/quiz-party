// ═══ ОБЩИЙ АУДИО-ЭЛЕМЕНТ «УГАДАЙ МЕЛОДИИ» ═══
// Вынесено из MelodyRound.tsx (HANDOFF.md §3bu) — чтобы тест гонки мог
// импортировать РЕАЛЬНЫЙ код напрямую, а не копию. Копия в тестовом файле
// уже один раз разошлась бы с реальным кодом незаметно: тест на неё
// оставался бы зелёным, даже убери кто-нибудь sharedGen из настоящего кода.
//
// Единый аудио-элемент: «разблокируется» первым кликом по проектору и дальше
// переиспользуется — autoplay-политика браузера больше не блокирует треки,
// запущенные выбором с телефона (там нет жеста на проекторе).
import { playAudio, createAudio } from './audioSource'

let sharedAudio: HTMLAudioElement | null = null
// Счётчик поколений — тот же паттерн, что у playSynced в audioSource.ts.
// playAudio() при блокировке прямого запроса СКАЧИВАЕТ файл через fetch
// (может занять несколько секунд) и уже ПОСЛЕ этого сама вызывает play()
// второй раз. Без счётчика это воспроизведение стартовало без предупреждения
// в уже другой стадии — трек играл сам, во время bidding, без клика
// ведущего (см. HANDOFF.md, критичный баг после 9.54).
let sharedGen = 0

export function unlockAudio() {
  if (sharedAudio) return
  sharedAudio = createAudio()
  // тихий пинок, чтобы браузер пометил элемент как «разрешённый жестом»
  sharedAudio.play().catch(() => {})
  sharedAudio.pause()
}

export function playShared(src: string, startAt = 0): HTMLAudioElement {
  if (!sharedAudio) sharedAudio = createAudio()
  const el = sharedAudio
  sharedGen++
  const my = sharedGen
  el.pause()
  el.loop = false
  el.volume = 1
  const isStale = () => my !== sharedGen
  // тот же запасной путь, что и в «Своей игре»: при блокировке прямого
  // запроса файл скачивается и играется из памяти. isStale передаём внутрь:
  // пока грузился запасной путь (fetch), могли уже уйти в другую стадию
  // (guard-таймер принудительно перевёл дальше) — playAudio сам не станет
  // проигрывать устаревший трек, вместо тихого запуска-и-паузы после факта.
  void playAudio(el, src, startAt, isStale).then((r) => {
    // Пауза нужна ТОЛЬКО если это воспроизведение реально запустило звук
    // (r.ok===true), а устаревшим оказалось уже ПОСЛЕ — путь 1 (прямой
    // play() без fetch), где isStale внутри playAudio не проверяется, потому
    // что скачивания не было. Если playAudio сама вернула ok:false (в т.ч.
    // reason:'stale' — она уже увидела чужое поколение ДО повторного play()
    // на запасном пути и ничего не тронула), el.pause() трогать НЕЛЬЗЯ: на
    // элементе к этому моменту может реально играть уже СЛЕДУЮЩИЙ трек, и
    // безусловный pause() его бы оборвал без причины.
    if (r.ok && isStale()) { try { el.pause() } catch { /* уже мёртв */ } }
  })
  return el
}

/** Заглушить общий трек. Нужен, когда ход уходит дальше сам: иначе музыка
 *  продолжает играть уже над следующей командой. Бампает поколение ДАЖЕ
 *  если ничего нового не запускается следом — иначе воспроизведение,
 *  которое ещё догружается в фоне (см. playShared), всё равно стартует
 *  после этой «остановки». */
export function stopShared() {
  sharedGen++
  if (!sharedAudio) return
  try { sharedAudio.pause(); sharedAudio.currentTime = 0 } catch { /* уже мёртв */ }
}

/** Только для тестов: сбросить общий элемент/поколение между кейсами —
 *  модуль иначе держит состояние между тестовыми файлами (переменные
 *  модуля живут дольше одного `it`). */
export function _resetSharedAudioForTests() {
  sharedAudio = null
  sharedGen = 0
}
