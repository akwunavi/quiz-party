-- последний раз играли этот pack_id» неоткуда — teams/answers ссылаются
-- на game_id, а не на pack_id напрямую. Нужно для issue #3 (выгрузка
-- статистики последней игры пакета прямо из редактора, без активной
-- комнаты).
-- ═══════════════════════════════════════════════════════════════

alter table packs add column if not exists last_game_id uuid;
