-- ПРОГНАТЬ ВРУЧНУЮ на единственной живой базе (ivan-quiz-party.ru).
-- У модели нет доступа к этой базе — она НЕ применяет миграцию сама.
-- Проверка — ОТДЕЛЬНЫМ файлом `0016_server_now_verify.sql` ПОСЛЕ этого
-- (не склеивать: begin…rollback в одном прогоне откатит и миграцию).
--
-- Идемпотентна (create or replace): повторный прогон ничего не ломает.
-- Ничего не меняет в таблицах и данных — только добавляет функцию.
--
-- Зачем: проектор, пульт и телефоны сравнивают «сейчас» со временем,
-- записанным ДРУГИМ устройством (старт таймера, дедлайны мелодии, защита
-- «Скрэмбла»). Часы устройств расходятся на секунды и минуты — таймеры
-- рассинхронизировались, кнопки блокировались. Клиент (src/lib/serverClock.ts)
-- раз в несколько минут спрашивает эту функцию, замеряет задержку и держит
-- поправку «часы базы − мои часы»; все экраны считают время с этой поправкой.
-- Если функции нет (миграция не прогнана) — клиент молча работает по своим
-- часам, как раньше.
-- ═══════════════════════════════════════════════════════════════

create or replace function public.server_now()
returns timestamptz
language sql
stable
as $$ select clock_timestamp() $$;

-- читать время может любой вход (проектор/телефоны без логина тоже)
grant execute on function public.server_now() to anon, authenticated;
